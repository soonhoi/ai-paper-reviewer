function clean(value) {
  return String(value ?? "").replace(/sk-[A-Za-z0-9_-]{16,}/g,"[REDACTED]").replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g,"").replace(/\t/g,"    ").normalize("NFC");
}
function reportData(full) {
  if(!full || !["ko","en"].includes(full.language) || !full.finalReview) throw new PdfReportError("리뷰 결과가 올바르지 않습니다.");
  const f=full.finalReview;
  if(!f.paperTitle || !f.scores || !f.metaReviewerConfidence || !["STRONG_ACCEPT","ACCEPT","WEAK_ACCEPT","BORDERLINE","WEAK_REJECT","REJECT","STRONG_REJECT"].includes(f.finalVerdict)) throw new PdfReportError("최종 리뷰 결과가 올바르지 않습니다.");
  for(const value of [f.scores.overall,f.metaReviewerConfidence.score])if(!Number.isInteger(value)||value<1||value>10)throw new PdfReportError("보고서 점수가 올바르지 않습니다.");
  const lists=["keyStrengths","keyWeaknesses","remainingConcerns","criticalBlockingIssues","requiredImprovements","optionalImprovements"];
  for(const key of lists)if(!Array.isArray(f[key])||f[key].some(v=>typeof v!=="string"))throw new PdfReportError("보고서 목록이 올바르지 않습니다.");
  // Whitelist report content. Credentials/client objects never enter the generator.
  return {language:full.language,finalReview:{
    paperTitle:clean(f.paperTitle),finalVerdict:f.finalVerdict,overall:f.scores.overall,confidence:f.metaReviewerConfidence.score,
    overallAssessment:clean(f.overallAssessment),verdictReason:clean(f.verdictReason),
    ...Object.fromEntries(lists.map(key=>[key,f[key].map(clean)])),
    mostImportantContribution:{contribution:clean(f.mostImportantContribution?.contribution),reason:clean(f.mostImportantContribution?.reason)},
    mostImportantWeakness:{weakness:clean(f.mostImportantWeakness?.weakness),reason:clean(f.mostImportantWeakness?.reason)},
  },debates:(full.debate?.debates || []).filter(issue=>["UNRESOLVED","PARTIALLY_RESOLVED"].includes(issue.resolution)).map(issue=>({
    issue:clean(issue.issue),resolution:issue.resolution,remainingConcern:clean(issue.remainingConcern),category:clean(issue.category),
  })),review:clean(full.review?.overallAssessment).slice(0,1600),advocate:clean(full.advocate?.overallDefense).slice(0,1600)};
}
function safeReportFilename(title) {
  const name=clean(title).replace(/[<>:"/\\|?*\u0000-\u001f]/g,"_").replace(/\s+/g,"_").replace(/[. ]+$/g,"").slice(0,100);
  return `${name || "AI-Paper"}_Review.pdf`;
}
async function chooseFont(content, options) {
  if(!/[^\x20-\x7e\r\n]/.test(content))return "Helvetica";
  const roots=[join(process.env.WINDIR || "C:/Windows","Fonts"),join(process.env.LOCALAPPDATA || "C:/Users/Default/AppData/Local","Microsoft","Windows","Fonts")];
  const paths=options.fontPaths ?? [process.env.REPORT_FONT_PATH,...roots.flatMap(root=>[join(root,"malgun.ttf"),join(root,"NanumGothic.ttf"),join(root,"NotoSansKR-Regular.ttf")])].filter(Boolean);
  const characters=[...new Set([...content].filter(ch=>!/[\r\n]/.test(ch)))];
  let found=false;
  for(const path of paths) {
    try {
      const font=fontkit.create(await readFile(path));
      if(typeof font.hasGlyphForCodePoint!=="function")continue;
      found=true;
      if(characters.every(ch=>font.hasGlyphForCodePoint(ch.codePointAt(0))))return font;
    } catch { /* Try the next installed Unicode font. */ }
  }
  throw new PdfReportError(found?"보고서 글자를 지원하는 Unicode 폰트가 없습니다.":"한글 Unicode 폰트를 찾지 못했습니다. Windows 한국어 폰트를 설치해 주세요.","REPORT_FONT");
}

async function generatePdfReport(full, options={}) {
  const data=reportData(full),f=data.finalReview,l=labels[data.language];
  const font=await chooseFont(JSON.stringify(data)+Object.values(l).join(" "),options);
  const doc=new PDFDocument({size:"A4",margins:{top:56,bottom:56,left:56,right:56},bufferPages:true,
    info:{Title:clean(`${l.title} - ${f.paperTitle}`),Author:"AI Paper Reviewer",Creator:"AI Paper Reviewer",Subject:"Academic paper review"}});
  const parts=[];
  const complete=new Promise((resolve,reject)=>{doc.on("data",part=>parts.push(part));doc.on("end",()=>resolve(Buffer.concat(parts)));doc.on("error",reject);});
  const width=doc.page.width-112;
  const ensure=(height)=>{if(doc.y+height>doc.page.height-56)doc.addPage();};
  const body=(value)=>{doc.font(font).fontSize(10.5).fillColor("#28342f").text(clean(value)||l.none,56,doc.y,{width,lineGap:4,paragraphGap:5});doc.moveDown(.45);};
  const section=(title)=>{ensure(64);doc.moveDown(.55);doc.font(font).fontSize(14).fillColor("#315c4b").text(title,56,doc.y,{width,lineGap:2});doc.moveDown(.4);};
  const list=(items)=>{if(!items.length)body(l.none);else items.forEach((item,i)=>{ensure(30);body(`${i+1}. ${item}`);});};
  doc.font(font).fontSize(21).fillColor("#244d42").text(l.title,{width});doc.moveDown(.7);
  doc.fontSize(10).fillColor("#65736b").text(l.paper);doc.moveDown(.25);
  doc.fontSize(15).fillColor("#20302e").text(f.paperTitle,{width,lineGap:3});doc.moveDown(.6);
  body(`${l.language}: ${data.language==="ko"?"Korean":"English"}\n${l.generated}: AI Paper Reviewer`);
  section(l.decision);
  doc.font(font).fontSize(16).fillColor("#244d42").text(`${l.verdict}: ${f.finalVerdict}`,{width});doc.moveDown(.4);
  body(`${l.score}: ${f.overall} / 10\n${l.confidence}: ${f.confidence} / 10`);
  for(const key of ["overallAssessment","keyStrengths","keyWeaknesses"]) {section(l[key]);Array.isArray(f[key])?list(f[key]):body(f[key]);}
  for(const [key,field] of [["mostImportantContribution","contribution"],["mostImportantWeakness","weakness"]]){
    section(l[key]);body(`${l[field]}: ${f[key][field]}\n\n${l.reason}: ${f[key].reason}`);
  }
  for(const key of ["remainingConcerns","criticalBlockingIssues","requiredImprovements","optionalImprovements","verdictReason"]){section(l[key]);Array.isArray(f[key])?list(f[key]):body(f[key]);}
  section(l.debate);
  const prioritized=[...data.debates].sort((a,b)=>(b.category==="criticalIssues")-(a.category==="criticalIssues"));
  if(!prioritized.length)body(l.none);
  prioritized.slice(0,8).forEach((item,i)=>body(`${i+1}. ${l.topic}: ${item.issue}\n${l.resolution}: ${item.resolution}\n${l.concern}: ${item.remainingConcern}`));
  if(prioritized.length>8)body(l.more);
  section(l.review);body(data.review || l.none);
  section(l.advocate);body(data.advocate || l.none);
  const range=doc.bufferedPageRange();
  for(let page=0;page<range.count;page++){
    doc.switchToPage(page);
    const bottom=doc.page.margins.bottom;
    doc.page.margins.bottom=0;
    doc.font(font).fontSize(8).fillColor("#6c7870");
    const y=doc.page.height-35;
    doc.text("AI Paper Reviewer",56,y,{width:width/2,lineBreak:false});
    doc.text(`Page ${page+1} / ${range.count}`,56+width/2,y,{width:width/2,align:"right",lineBreak:false});
    doc.page.margins.bottom=bottom;
  }
  doc.end();
  return complete;
}

async function savePdfReport({fullReview,showSaveDialog,generate=generatePdfReport,write=writeFile}) {
  if(!fullReview?.finalReview)throw new PdfReportError("저장할 리뷰 결과가 없습니다.");
  const result=await showSaveDialog({defaultPath:safeReportFilename(fullReview.finalReview.paperTitle),filters:[{name:"PDF Document",extensions:["pdf"]}]});
  if(result.canceled)return false;
  if(typeof result.filePath!=="string"||!result.filePath)throw new PdfReportError("저장 위치가 올바르지 않습니다.");
  let bytes;
  try{bytes=await generate(fullReview);}
  catch(error){if(error instanceof PdfReportError)throw error;throw new PdfReportError("PDF 보고서 생성 중 오류가 발생했습니다.");}
  // Preserve an existing PDF if generation or writing fails.
  const temp=join(dirname(result.filePath),`.paper-review-${randomUUID()}.tmp`);
  try{await write(temp,bytes);await rename(temp,result.filePath);}
  catch{throw new PdfReportError("PDF 보고서 파일을 저장하지 못했습니다.","REPORT_WRITE");}
  finally{await unlink(temp).catch(()=>{});}
  return true;
}
exports.generatePdfReport=generatePdfReport;
exports.savePdfReport=savePdfReport;
exports.safeReportFilename=safeReportFilename;
exports.PdfReportError=PdfReportError;
